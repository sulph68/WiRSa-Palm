#!/usr/bin/env python3
"""Generate src/modules/translit_data.cpp (Chinese -> pinyin, kana -> romaji tables).

    python3 tools/gen_translit.py /path/to/Unihan_Readings.txt > src/modules/translit_data.cpp

Unihan_Readings.txt is in Unihan.zip from https://www.unicode.org/Public/UCD/latest/ucd/
(Unicode license). Each CJK ideograph U+3400..U+9FFF gets the first kMandarin reading
(the most customary one), else the first kHanyuPinyin reading, with tones and the
umlaut removed. The generated file is committed: building needs neither Python nor Unihan.
"""
import sys, unicodedata

HAN_FIRST, HAN_LAST = 0x3400, 0x9FFF

def plain(p):
    p = unicodedata.normalize('NFD', p)
    p = ''.join(c for c in p if not unicodedata.combining(c))
    return p.lower()

mand, hanyu = {}, {}
for line in open(sys.argv[1], encoding='utf8'):
    if line.startswith('#') or not line.strip():
        continue
    cp, key, val = line.rstrip('\n').split('\t', 2)
    c = int(cp[2:], 16)
    if not (HAN_FIRST <= c <= HAN_LAST):
        continue
    if key == 'kMandarin':
        mand[c] = plain(val.split()[0])
    elif key == 'kHanyuPinyin' and c not in hanyu:
        r = val.split()[0].split(':')[-1].split(',')[0]
        hanyu[c] = plain(r)
read = {}
for c in range(HAN_FIRST, HAN_LAST + 1):
    s = mand.get(c) or hanyu.get(c)
    if s:
        read[c] = s
syl = sorted(set(read.values()))
assert max(len(s) for s in syl) <= 6 and len(syl) < 65535
sidx = {s: i + 1 for i, s in enumerate(syl)}

# kana -> romaji (Hepburn) from the Unicode character names
FIX = {'si': 'shi', 'ti': 'chi', 'tu': 'tsu', 'hu': 'fu', 'zi': 'ji', 'di': 'ji', 'du': 'zu',
       'ya': 'ya', 'yu': 'yu', 'yo': 'yo'}
def kana(c):
    try:
        n = unicodedata.name(chr(c))
    except ValueError:
        return ''
    r = n.split()[-1].lower()
    if n.endswith(' SMALL TU') or r == 'tu':
        r = 'tu'
    return FIX.get(r, r)
hira = [kana(c) for c in range(0x3041, 0x3097)]       # 86
kata = [kana(c) for c in range(0x30A1, 0x30FB)]       # 90

out = []
w = out.append
w('// Generated by tools/gen_translit.py from Unicode Unihan (kMandarin / kHanyuPinyin); do not edit.')
w('// Unicode data files are under the Unicode License (https://www.unicode.org/license.txt).')
w('#include "translit_data.h"')
w('')
w('const char kPinyin[%d][7] = {' % len(syl))
for i in range(0, len(syl), 8):
    w('  ' + ', '.join('"%s"' % s for s in syl[i:i + 8]) + ',')
w('};')
w('const uint16_t kPinyinCount = %d;' % len(syl))
w('')
w('const uint16_t kHanIdx[%d] = {   // U+%04X..U+%04X: 0 = no reading, else kPinyin index + 1' % (HAN_LAST - HAN_FIRST + 1, HAN_FIRST, HAN_LAST))
vals = [sidx.get(read.get(c), 0) for c in range(HAN_FIRST, HAN_LAST + 1)]
for i in range(0, len(vals), 16):
    w('  ' + ','.join(str(v) for v in vals[i:i + 16]) + ',')
w('};')
w('')
w('const char kKana[%d][4] = {   // U+3041..U+3096 then U+30A1..U+30FA' % (len(hira) + len(kata)))
for name, tab in (('hiragana', hira), ('katakana', kata)):
    for i in range(0, len(tab), 8):
        w('  ' + ', '.join('"%s"' % s for s in tab[i:i + 8]) + ',')
w('};')
print('\n'.join(out))
sys.stderr.write('%d characters with a reading, %d syllables, %d kana\n' % (len(read), len(syl), len(hira) + len(kata)))
